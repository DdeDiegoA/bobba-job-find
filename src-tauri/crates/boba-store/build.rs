//! Build convention (AD-20): discover `migrations/NNNN_name.sql` by sorted file
//! name and embed their contents in the binary, so a new migration file needs no
//! code change. The generated table is included by `src/migrate/mod.rs`.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("migrations");
    println!("cargo:rerun-if-changed=migrations");

    let mut files: Vec<PathBuf> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()))
        .map(|entry| entry.expect("migrations dir entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "sql"))
        .collect();
    files.sort();

    let mut out =
        String::from("/// Embedded migrations, sorted by file name (generated by build.rs).\n");
    out.push_str("pub static MIGRATIONS: &[(&str, &str)] = &[\n");
    for file in &files {
        let name = file
            .file_name()
            .expect("migration file name")
            .to_string_lossy();
        let sql = fs::read_to_string(file)
            .unwrap_or_else(|e| panic!("cannot read {}: {e}", file.display()));
        writeln!(out, "    ({name:?}, {sql:?}),").expect("write to String");
    }
    out.push_str("];\n");

    let out_path =
        Path::new(&env::var("OUT_DIR").expect("OUT_DIR")).join("migrations_generated.rs");
    fs::write(out_path, out).expect("write generated migrations");
}
