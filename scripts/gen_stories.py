#!/usr/bin/env python3
"""Generate docs/product/stories.yaml from docs/product/epics-and-stories.md.

Usage: python3 scripts/gen_stories.py          # write stories.yaml
       python3 scripts/gen_stories.py --check  # exit 1 if stories.yaml is stale or invalid (CI)
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MD = ROOT / "docs/product/epics-and-stories.md"
PRD = ROOT / "docs/product/PRD.md"
OUT = ROOT / "docs/product/stories.yaml"

META = re.compile(r"\*\*Phase:\*\* (.*?) · \*\*Depends on:\*\* (.*?)(?: · \*\*Files:\*\* (.*?))? · \*\*Covers:\*\* (.*)")
IDS = re.compile(r"\b(?:FR|NFR|ADR|AD|SM|UJ)-\d+\b|EXPERIENCE §[\d.]+(?:, §[\d.]+)*")
FILE = re.compile(r"`([^`]+)`(?:\s*\(([^)]*)\))?")


def parse():
    stories = []
    for part in re.split(r"^### Story ", MD.read_text(), flags=re.M)[1:]:
        head, _, body = part.partition("\n")
        sid, title = head.split(":", 1)
        m = META.search(body)
        if not m:
            sys.exit(f"story {sid}: missing Phase/Depends/Covers line")
        phase, deps, files, covers = m.groups()
        stories.append({
            "id": sid.strip(),
            "epic": "E" + sid.split(".")[0],
            "title": title.replace("⚠", "").strip(),
            "phase": phase.strip(),
            "depends_on": [] if deps.strip() == "—" else [d.strip() for d in deps.split(",")],
            "files": [f"{p} ({n})" if n else p for p, n in FILE.findall(files or "")],
            "covers": list(dict.fromkeys(IDS.findall(covers))),
            "ac": [re.sub(r"\*\*", "", l[2:]).strip() for l in body.split("\n")
                   if l.startswith(("- **Given**", "- **And**"))],
        })
    return stories


def validate(stories):
    errs = []
    ids = {s["id"] for s in stories}
    phase = {s["id"]: s["phase"] for s in stories}
    for s in stories:
        for d in s["depends_on"]:
            if d not in ids:
                errs.append(f"{s['id']}: unknown dependency {d}")
            elif s["phase"] == "MVP" and phase[d] != "MVP":
                errs.append(f"{s['id']}: MVP story depends on {phase[d]} story {d}")
        if not s["ac"]:
            errs.append(f"{s['id']}: no acceptance criteria")
    graph, state = {s["id"]: s["depends_on"] for s in stories}, {}

    def visit(n):
        if state.get(n) == 1:
            errs.append(f"dependency cycle at {n}")
            return
        if state.get(n) == 2:
            return
        state[n] = 1
        for d in graph.get(n, []):
            visit(d)
        state[n] = 2
    for n in graph:
        visit(n)
    mvp = set(re.findall(r"#### (FR-\d+):[^\n]*\[MVP", PRD.read_text()))
    covered = {c for s in stories if s["phase"] == "MVP" for c in s["covers"]}
    for fr in sorted(mvp - covered, key=lambda x: int(x[3:])):
        errs.append(f"MVP {fr} not covered by any MVP story")
    return errs


def render(stories):
    q = lambda v: json.dumps(v, ensure_ascii=False)
    out = ["# Generated by scripts/gen_stories.py from docs/product/epics-and-stories.md — do not edit.",
           "version: 1", "stories:"]
    for s in stories:
        out += [f"  - id: {q(s['id'])}", f"    epic: {s['epic']}", f"    title: {q(s['title'])}",
                f"    phase: {q(s['phase'])}", f"    depends_on: {q(s['depends_on'])}",
                f"    files: {q(s['files'])}", f"    covers: {q(s['covers'])}", "    ac:"]
        out += [f"      - {q(a)}" for a in s["ac"]]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    stories = parse()
    errs = validate(stories)
    for e in errs:
        print("ERROR:", e)
    text = render(stories)
    if "--check" in sys.argv:
        stale = not OUT.exists() or OUT.read_text() != text
        if stale:
            print("ERROR: stories.yaml is stale; run scripts/gen_stories.py")
        sys.exit(1 if errs or stale else 0)
    OUT.write_text(text)
    n_mvp = sum(s["phase"] == "MVP" for s in stories)
    print(f"{len(stories)} stories ({n_mvp} MVP) -> {OUT.relative_to(ROOT)}")
    sys.exit(1 if errs else 0)
