#!/usr/bin/env bash
# One-time setup of the persistent project-owned macOS signing identity
# (ADR-009, S10.5 AC3). Run this ONCE by a maintainer, then keep the private key
# offline and store the .p12 as the MACOS_CERTIFICATE secret.
#
#   scripts/release/generate-macos-identity.sh --out ~/boba-signing
#
# It writes:
#   boba-signing.key      the private key (never commit, never share)
#   boba-signing.crt      the self-signed certificate
#   boba-signing.p12      the certificate + key, password-protected (CI secret material)
#   boba-signing.password the .p12 password (store as MACOS_CERTIFICATE_PASSWORD)
# and pins the certificate leaf hash in scripts/release/macos-identity.pin.
#
# Why one identity forever: macOS Keychain items are bound to the creating
# binary's designated requirement. A stable certificate leaf keeps the DB key
# readable across updates; an ad-hoc build would change it every release.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
OUT=""
CN="Boba Job Find Self-Signed"
WRITE_PIN=1

while [ $# -gt 0 ]; do
  case "$1" in
    --out) OUT="${2:?--out needs a directory}"; shift 2 ;;
    --cn) CN="${2:?--cn needs a value}"; shift 2 ;;
    --no-pin) WRITE_PIN=0; shift ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

if [ -z "$OUT" ]; then
  echo "usage: $0 --out <directory> [--cn <common name>] [--no-pin]" >&2
  exit 2
fi
if [ "$(uname -s)" != "Darwin" ]; then
  echo "this script creates an Apple code-signing identity and only runs on macOS" >&2
  exit 1
fi

umask 077
mkdir -p "$OUT"
OUT="$(cd "$OUT" && pwd)"

KEY="$OUT/boba-signing.key"
CRT="$OUT/boba-signing.crt"
P12="$OUT/boba-signing.p12"
PWFILE="$OUT/boba-signing.password"

if [ -e "$KEY" ] && [ "$WRITE_PIN" -eq 1 ]; then
  echo "refusing to overwrite $KEY (a lost or rotated identity forces every user to re-approve the keychain); pass --no-pin with a new --out directory" >&2
  exit 1
fi

echo "generating the self-signed code-signing certificate…"
openssl req -x509 -newkey rsa:3072 -sha256 -days 7300 -nodes \
  -keyout "$KEY" -out "$CRT" \
  -subj "/CN=$CN/O=Boba Job Find" \
  -addext "basicConstraints=critical,CA:FALSE" \
  -addext "keyUsage=critical,digitalSignature" \
  -addext "extendedKeyUsage=critical,codeSigning"

PASSWORD="$(openssl rand -base64 24)"
printf '%s' "$PASSWORD" > "$PWFILE"
chmod 600 "$KEY" "$PWFILE"

# macOS's Security framework rejects OpenSSL 3's default PBES2/AES-256 p12
# ("MAC verification failed during PKCS12 import"), so export the legacy
# RC2/3DES container. It is only an import vehicle for the trusted keychain; the
# key itself stays protected by the password and never leaves the maintainer.
openssl pkcs12 -export -legacy -inkey "$KEY" -in "$CRT" -out "$P12" -name "$CN" \
  -passout "pass:$PASSWORD"

FINGERPRINT="$(openssl x509 -in "$CRT" -noout -fingerprint -sha1 | sed 's/.*=//' | tr -d ':' | tr 'A-F' 'a-f')"
if ! printf '%s' "$FINGERPRINT" | grep -Eq '^[0-9a-f]{40}$'; then
  echo "could not read the certificate fingerprint for the pin" >&2
  exit 1
fi

if [ "$WRITE_PIN" -eq 1 ]; then
  cat > "$HERE/macos-identity.pin" <<EOF
# Pinned designated-requirement certificate (ADR-009). Generated by
# scripts/release/generate-macos-identity.sh; do not edit by hand.
# Every macOS build — release, beta or CI artifact — must be signed with this
# certificate leaf, or Keychain access will not survive the next update.
BOBA_MACOS_CERT_SHA1=$FINGERPRINT
EOF
  echo "pinned certificate leaf in scripts/release/macos-identity.pin"
fi

echo
echo "identity:   $CN"
echo "leaf SHA-1: $FINGERPRINT"
echo
echo "Next steps (one time):"
echo "  1. Store the .p12 as the repository secret MACOS_CERTIFICATE:"
printf '       openssl base64 -A -in %q\n' "$P12"
echo "  2. Store $PWFILE as MACOS_CERTIFICATE_PASSWORD."
echo "  3. Keep $KEY and $PWFILE in an offline maintainer backup. Losing them"
echo "     forces every macOS user to approve the Keychain item once."
echo "  4. Commit scripts/release/macos-identity.pin."
